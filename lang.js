// دالة تبديل اللغة
function switchLang() {
  // بنجيب اللغة الحالية، ولو مش موجودة بنكتبها "en" (إنجليزي افتراضي)
  const current = localStorage.getItem("lang") || "en";
  // بنعكسها، لو إنجليزي نخليها عربي والعكس صحيح
  localStorage.setItem("lang", current === "en" ? "ar" : "en");
  // بنعمل ريفرش للصفحة عشان تاخد اللغة الجديدة وتترجم بناءً عليها
  window.location.reload();
}

// دي الدالة الذكية اللي بتلف على كل عنصر فيه خاصية (data-i18n) وتعوض مكانها بالترجمة المناسبة
function applyTranslations(dict, lang) {
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[lang] && dict[lang][key]) {
      // check if it is an input to translate placeholder
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.hasAttribute('placeholder')) {
           el.placeholder = dict[lang][key];
        } else {
           el.innerHTML = dict[lang][key];
        }
      } else {
        el.innerHTML = dict[lang][key];
      }
    }
  });
}

// دالة بتتعامل مع أكوادنا جوة الجافاسكريبت مش الـ HTML، عشان نترجم بيها النصوص اللي بتتبني جوه الدوال
window.t = function(key) {
  const current = localStorage.getItem("lang") || "en";
  return (dictionary[current] && dictionary[current][key]) ? dictionary[current][key] : key;
};

