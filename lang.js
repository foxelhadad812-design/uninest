function appendMsg(sender, text) {
  const body = document.getElementById('chatbotBody');
  const div = document.createElement('div');
  div.className = "chat-msg " + sender;
  div.innerHTML = text;
  body.appendChild(div);
  body.scrollTop = body.scrollHeight;
}
